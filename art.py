def _face(top, brow, eyes, nose, mouth, neck, chest):
    """Assemble a bust: 5-char brow, 7-char eyes/nose/mouth rows."""
    return "\n".join(["", top, f"    /{brow}\\", f"   |{eyes}|", f"   |{nose}|", f"   |{mouth}|",
                      "    \\_____/", neck, chest, ""])


def _volkov(eyes, mouth):
    return "\n".join(["", "    _______", "  _|_______|_", f"   |{eyes}|", "   |   \\   |", f"   |{mouth}|",
                      "    \\__/__/", "   ___| |___", r"  /   |V|   \ ", ""])


